#!/bin/bash -e
# ZPOD M2 (display + audio + buttons + USB gadget) — pi-gen stage2 substep.
# Installed by build/tweaks/apply.sh as stage2/05-zpod-m2. Runs on the host
# with ROOTFS_DIR set; chroot work goes through on_chroot.

BOOTFW="${ROOTFS_DIR}/boot/firmware"

# 1. Static files (code, units, ALSA/NM/journald/modprobe config)
(
	cd files/overlay
	find . -type f -print0 | while IFS= read -r -d '' f; do
		install -D -o root -g root -m "$(stat -c %a "$f")" "$f" "${ROOTFS_DIR}/${f#./}"
	done
)
install -d -m 2755 -o root -g systemd-journal "${ROOTFS_DIR}/var/log/journal" 2>/dev/null \
	|| install -d -m 2755 "${ROOTFS_DIR}/var/log/journal"
install -d -m 755 "${ROOTFS_DIR}/var/lib/zpod"

# 2. Gadget netdev (usb0) must be managed by NetworkManager. NM's
#    85-nm-unmanaged.rules unmanages DEVTYPE=gadget by default.
cat > "${ROOTFS_DIR}/etc/udev/rules.d/86-zpod-usb-gadget-nm-managed.rules" <<- 'RULE'
	# ZPOD: let NetworkManager manage the USB gadget Ethernet (usb0)
	ENV{DEVTYPE}=="gadget", ENV{NM_UNMANAGED}="0"
RULE
cat > "${ROOTFS_DIR}/etc/NetworkManager/conf.d/90-zpod-usb0-managed.conf" <<- 'CONF'
	# ZPOD: manage the USB gadget Ethernet (overrides the udev default)
	[device-zpod-usb0]
	match-device=interface-name:usb0
	managed=1
CONF

# 3. NetworkManager profiles for usb0, same names/addresses as Raspberry Pi's
#    rpi-usb-gadget ("on"), so `rpi-usb-gadget status` and its ICS watcher
#    work unchanged. SHARED: Pi serves DHCP on 10.12.194.0/28 (Pi = .1).
#    CLIENT: used only if the Mac enables Internet Sharing (ics-watch flips).
NMC="${ROOTFS_DIR}/etc/NetworkManager/system-connections"
install -d -m 700 "$NMC"
cat > "$NMC/usb-gadget-shared.nmconnection" <<- 'NM'
	[connection]
	id=USB Gadget (shared)
	uuid=7a6b2f1e-3c55-4d1a-9e0b-5a504f440001
	type=ethernet
	interface-name=usb0
	autoconnect=true
	autoconnect-priority=10

	[ethernet]

	[ipv4]
	method=shared
	address1=10.12.194.1/28

	[ipv6]
	addr-gen-mode=default
	method=link-local

	[proxy]
NM
cat > "$NMC/usb-gadget-client.nmconnection" <<- 'NM'
	[connection]
	id=USB Gadget (client)
	uuid=7a6b2f1e-3c55-4d1a-9e0b-5a504f440002
	type=ethernet
	interface-name=usb0
	autoconnect=false
	autoconnect-priority=100

	[ethernet]

	[ipv4]
	method=auto
	may-fail=true
	route-metric=100
	dhcp-timeout=6

	[ipv6]
	method=disabled

	[proxy]
NM
chmod 600 "$NMC"/usb-gadget-*.nmconnection
chown root:root "$NMC"/usb-gadget-*.nmconnection
install -d -m 755 "${ROOTFS_DIR}/etc/NetworkManager/dnsmasq-shared.d"
cat > "${ROOTFS_DIR}/etc/NetworkManager/dnsmasq-shared.d/90-rpi-usb-gadget-lease.conf" <<- 'DNSM'
	# Autogenerated by rpi-usb-gadget – safe to delete
	dhcp-authoritative
	dhcp-option=51,120
	quiet-dhcp
DNSM

# 4. Boot config: in-place base-DT dtparams (must precede any dtoverlay= line,
#    otherwise they bind to that overlay), then overlays/gpio in [all].
CFG="${BOOTFW}/config.txt"
sed -i \
	-e 's/^#\?dtparam=i2c_arm=on/dtparam=i2c_arm=on/' \
	-e 's/^#\?dtparam=i2s=on/dtparam=i2s=on/' \
	-e 's/^#\?dtparam=spi=on/dtparam=spi=on/' \
	-e 's/^dtparam=audio=on/dtparam=audio=off/' \
	"$CFG"
grep -q '^dtparam=i2c_arm=on' "$CFG"
grep -q '^dtparam=i2s=on' "$CFG"
grep -q '^dtparam=spi=on' "$CFG"
grep -q '^dtparam=audio=off' "$CFG"
if ! grep -q 'ZPOD M2' "$CFG"; then
	tail -n1 "$CFG" | grep -q '^\[all\]' || printf '\n[all]\n' >> "$CFG"
	cat >> "$CFG" <<- 'CFGEOF'
		# --- ZPOD M2 (hardware confirmed on Pi Zero W, 2026-10-07) ---
		# Aoide ZPOD DAC: PCM5122 on I2C1 @ 0x4d, I2S (overlay from aoide-zpod-dac-dkms)
		dtoverlay=aoide-zpod-dac
		# Headphone amp is muted unless GPIO14 is LOW (GPIO14 is also UART TX)
		gpio=14=op,dl
		# Buttons: inputs with pull-ups at firmware time (GPIO20 = I2S DIN: pull
		# set at runtime by zpod-buttons only; never re-muxed)
		gpio=4,5,6,12,13,16,17,22,23,24,26=ip,pu
		# USB gadget Ethernet on the data port (Raspberry Pi rpi-usb-gadget line)
		dtoverlay=dwc2,dr_mode=peripheral
	CFGEOF
fi

# 5. cmdline: drop the serial console (GPIO14 = UART TX = amp mute line)
sed -i -e 's/console=serial0,[0-9]* *//' "${BOOTFW}/cmdline.txt"
! grep -q 'console=serial0' "${BOOTFW}/cmdline.txt"

# 6. DAC driver via DKMS (builds for every kernel with headers: rpi-v6, rpi-v7)
install -m 644 files/aoide-zpod-dac-dkms_*_all.deb "${ROOTFS_DIR}/tmp/"
on_chroot <<- 'CHROOT'
	set -e
	dpkg -i /tmp/aoide-zpod-dac-dkms_*_all.deb
	rm -f /tmp/aoide-zpod-dac-dkms_*_all.deb
	dkms status
	for d in /lib/modules/*; do
		k=$(basename "$d")
		[ -e "$d/build/Makefile" ] || continue
		ls "$d"/updates/dkms/aoide-zpod-dac.ko* >/dev/null
		modinfo -k "$k" aoide-zpod-dac | grep -E '^(filename|vermagic|alias):'
	done
CHROOT
for d in "${ROOTFS_DIR}"/lib/modules/*-rpi-v6; do
	ls "$d"/updates/dkms/aoide-zpod-dac.ko* >/dev/null
done

# 7. Services
on_chroot <<- 'CHROOT'
	set -e
	systemctl enable zpod-buttons.service zpod-ui.service zpod-audio-init.service
	systemctl enable rpi-usb-gadget-ics.service
	systemctl is-enabled zpod-buttons.service zpod-ui.service zpod-audio-init.service rpi-usb-gadget-ics.service
	python3 -c "import spidev, lgpio, evdev, PIL, smbus2; import sys; sys.path.insert(0, '/usr/lib/zpod'); import zpod_hw, zpod_lcd; print('zpod python imports ok')"
	python3 -m py_compile /usr/lib/zpod/zpod_ui.py /usr/lib/zpod/zpod_buttons.py
CHROOT
